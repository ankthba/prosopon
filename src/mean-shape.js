/** Centre, scale to unit centroid size. */
export function normaliseShape(pts) {
  const n = pts.length;
  let cx = 0, cy = 0;
  for (const p of pts) { cx += p.x; cy += p.y; }
  cx /= n; cy /= n;
  const c = pts.map((p) => ({ x: p.x - cx, y: p.y - cy }));
  let s = 0;
  for (const p of c) s += p.x * p.x + p.y * p.y;
  const k = Math.sqrt(s / n) || 1;
  return c.map((p) => ({ x: p.x / k, y: p.y / k }));
}

/** Optimal in-plane rotation of `s` onto `ref` (2-D Kabsch). */
export function rotateOnto(s, ref) {
  let num = 0, den = 0;
  for (let i = 0; i < s.length; i++) {
    num += s[i].x * ref[i].y - s[i].y * ref[i].x;
    den += s[i].x * ref[i].x + s[i].y * ref[i].y;
  }
  const th = Math.atan2(num, den), c = Math.cos(th), si = Math.sin(th);
  return s.map((p) => ({ x: p.x * c - p.y * si, y: p.x * si + p.y * c }));
}

/** Procrustes distance from a landmark set to the reference mean shape. */
export function procrustesDistance(pts468) {
  const ref = [];
  for (let i = 0; i < MEAN_SHAPE.length; i += 2) ref.push({ x: MEAN_SHAPE[i], y: MEAN_SHAPE[i + 1] });
  const s = rotateOnto(normaliseShape(pts468.slice(0, 468)), ref);
  let acc = 0;
  for (let i = 0; i < ref.length; i++) acc += (s[i].x - ref[i].x) ** 2 + (s[i].y - ref[i].y) ** 2;
  return { distance: Math.sqrt(acc / ref.length), aligned: s, reference: ref };
}
